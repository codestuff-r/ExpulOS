
#include "types.h"
#include "x86.h"
#include "memlayout.h"

#define VGA_WIDTH 320
#define VGA_HEIGHT 200
#define VGA_FB ((volatile uchar*)P2V(0xA0000))

static uchar misc13 = 0x63;
static uchar seq13[5] = {0x03,0x01,0x0F,0x00,0x0E};
static uchar crtc13[25] = {
  0x5F,0x4F,0x50,0x82,0x54,0x80,0xBF,0x1F,
  0x00,0x41,0x00,0x00,0x00,0x00,0x00,0x00,
  0x9C,0x0E,0x8F,0x28,0x40,0x96,0xB9,0xA3,0xFF
};
static uchar gc13[9] = {
  0x00,0x00,0x00,0x00,0x00,0x40,0x05,0x0F,0xFF
};
static uchar attr13[21] = {
  0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
  0x08,0x09,0x0A,0x0B,0x0C,0x0D,0x0E,0x0F,
  0x41,0x00,0x0F,0x00,0x00
};

static uchar misc3 = 0x67;
static uchar seq3[5] = {0x03,0x00,0x03,0x00,0x02};
static uchar crtc3[25] = {
  0x5F,0x4F,0x50,0x82,0x55,0x81,0xBF,0x1F,
  0x00,0x4F,0x0D,0x0E,0x00,0x00,0x00,0x50,
  0x9C,0x0E,0x8F,0x28,0x1F,0x96,0xB9,0xA3,0xFF
};
static uchar gc3[9] = {
  0x00,0x00,0x00,0x00,0x00,0x10,0x0E,0x00,0xFF
};
static uchar attr3[21] = {
  0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
  0x08,0x09,0x0A,0x0B,0x0C,0x0D,0x0E,0x0F,
  0x0C,0x00,0x0F,0x08,0x00
};

static void
write_regs(uchar misc, uchar *seq, uchar *crtc,
           uchar *gc, uchar *attr)
{
  int i;

  outb(0x3C2, misc);

  for(i = 0; i < 5; i++){
    outb(0x3C4, i);
    outb(0x3C5, seq[i]);
  }

  outb(0x3D4, 0x03);
  outb(0x3D5, inb(0x3D5) | 0x80);
  outb(0x3D4, 0x11);
  outb(0x3D5, inb(0x3D5) & 0x7F);

  for(i = 0; i < 25; i++){
    outb(0x3D4, i);
    outb(0x3D5, crtc[i]);
  }

  for(i = 0; i < 9; i++){
    outb(0x3CE, i);
    outb(0x3CF, gc[i]);
  }

  for(i = 0; i < 21; i++){
    inb(0x3DA);
    outb(0x3C0, i);
    outb(0x3C0, attr[i]);
  }

  inb(0x3DA);
  outb(0x3C0, 0x20);
}

int
vga_set_mode(int mode)
{
  int i;

  if(mode == 13){
    write_regs(misc13, seq13, crtc13, gc13, attr13);

    for(i = 0; i < VGA_WIDTH * VGA_HEIGHT; i++)
      VGA_FB[i] = 0;

    return 0;
  }

  if(mode == 3){
    write_regs(misc3, seq3, crtc3, gc3, attr3);
    return 0;
  }

  return -1;
}

int
vga_putpixel(int x, int y, int color)
{
  if(x < 0 || x >= VGA_WIDTH ||
     y < 0 || y >= VGA_HEIGHT ||
     color < 0 || color > 255)
    return -1;

  VGA_FB[y * VGA_WIDTH + x] = (uchar)color;
  return 0;
}

int
vga_fillrect(int x, int y, int w, int h, int color)
{
  int row, col;

  if(w <= 0 || h <= 0 || color < 0 || color > 255)
    return -1;

  if(x < 0){ w += x; x = 0; }
  if(y < 0){ h += y; y = 0; }

  if(x >= VGA_WIDTH || y >= VGA_HEIGHT || w <= 0 || h <= 0)
    return 0;

  if(w > VGA_WIDTH - x) w = VGA_WIDTH - x;
  if(h > VGA_HEIGHT - y) h = VGA_HEIGHT - y;

  for(row = 0; row < h; row++)
    for(col = 0; col < w; col++)
      VGA_FB[(y + row) * VGA_WIDTH + x + col] = (uchar)color;

  return 0;
}
